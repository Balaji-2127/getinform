// Lays the narration onto the screen recording and writes the final video.
//
// record.mjs logs the wall-clock offset at which each walkthrough step began;
// this places that step's narration at exactly that offset. Nothing is
// concatenated, so a clip that changes length cannot shift the ones after it
// — which is what makes the narration swappable for a human recording
// without re-recording the screen.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, statSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { steps } from "./walkthrough.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const work = join(here, ".rec");
const RAW = join(work, "raw.mp4");
const MARKS = join(work, "marks.json");
const OUT = process.env.OUT || join(root, "public", "demo.mp4");

if (!existsSync(RAW)) throw new Error(`no recording at ${RAW} — run record.mjs first`);
if (!existsSync(MARKS)) throw new Error(`no marks at ${MARKS} — run record.mjs first`);
mkdirSync(dirname(OUT), { recursive: true });

const probe = (f) =>
  Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], { encoding: "utf8" }).trim());

const marks = JSON.parse(readFileSync(MARKS, "utf8"));
const videoDur = probe(RAW);

const tracks = [];
for (const m of marks) {
  const wav = join(here, "narration", `${m.id}.wav`);
  if (!existsSync(wav)) {
    console.log(`  (no narration for ${m.id} — silent)`);
    continue;
  }
  const dur = probe(wav);
  if (m.at + dur > videoDur + 1) {
    console.log(`  !! ${m.id} runs past the end of the recording — trimmed by ffmpeg`);
  }
  tracks.push({ ...m, wav, dur });
}

console.log(`recording ${videoDur.toFixed(1)}s, ${tracks.length} narration tracks`);

const inputs = ["-i", RAW];
for (const t of tracks) inputs.push("-i", t.wav);

const parts = [];
tracks.forEach((t, i) => {
  // +0.35s so the voice starts just after the action it describes becomes
  // visible, rather than landing exactly on the transition.
  const delayMs = Math.round((t.at + 0.35) * 1000);
  parts.push(
    `[${i + 1}:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo,adelay=${delayMs}|${delayMs}[a${i}]`,
  );
});
// normalize=0 because these lines never overlap — with the default, amix
// would divide every clip's level by the track count and the voice would
// all but disappear. That is why the first cut sounded like it had no audio.
parts.push(`${tracks.map((_, i) => `[a${i}]`).join("")}amix=inputs=${tracks.length}:normalize=0:dropout_transition=0[mixed]`);
// Brought up to a consistent broadcast-ish level. The previous build averaged
// -22.9 dB, quiet enough that on a laptop at normal volume it read as silent.
parts.push(`[mixed]loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000[a]`);
parts.push(`[0:v]fade=t=in:st=0:d=0.5,fade=t=out:st=${(videoDur - 0.8).toFixed(2)}:d=0.8[v]`);

console.log("muxing…");
execFileSync(
  "ffmpeg",
  [
    "-hide_banner", "-loglevel", "error", "-y",
    ...inputs,
    "-filter_complex", parts.join(";"),
    "-map", "[v]",
    "-map", "[a]",
    "-c:v", "libx264",
    "-preset", "slow",
    // Screen content, not camera footage: flat colour fields with fine text
    // on top. `stillimage` keeps the bitrate on the edges — the letterforms
    // the viewer actually has to read.
    "-tune", "stillimage",
    "-crf", "23",
    "-pix_fmt", "yuv420p",
    "-movflags", "+faststart",
    "-c:a", "aac",
    "-b:a", "160k",
    OUT,
  ],
  { stdio: ["ignore", "inherit", "inherit"] },
);

const poster = join(root, "public", "demo-poster.jpg");
execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-ss", "2", "-i", OUT, "-frames:v", "1", "-q:v", "3", poster]);

// Chapter offsets come straight from the recorded marks, so the in-app list
// cannot drift out of step with what is actually on screen.
const chapters = steps
  .map((s) => {
    const m = marks.find((x) => x.id === s.id);
    return m ? { id: s.id, at: Number(m.at.toFixed(2)), label: s.caption || s.say.slice(0, 48) } : null;
  })
  .filter(Boolean)
  .filter((c) => !["01-intro", "27-close"].includes(c.id));

const { writeFileSync } = await import("node:fs");
writeFileSync(
  join(root, "src", "dashboard", "demoChapters.ts"),
  `// GENERATED by video/mux.mjs — do not edit by hand.\n` +
    `// Regenerate with: node video/mux.mjs\n` +
    `export type DemoChapter = { id: string; at: number; label: string };\n\n` +
    `export const DEMO_DURATION = ${videoDur.toFixed(2)};\n\n` +
    `export const DEMO_CHAPTERS: DemoChapter[] = ${JSON.stringify(chapters, null, 2)};\n`,
  "utf8",
);

const dur = probe(OUT);
console.log(`\n${OUT}`);
console.log(`${(statSync(OUT).size / 1024 / 1024).toFixed(1)} MB  ${Math.floor(dur / 60)}:${String(Math.round(dur % 60)).padStart(2, "0")}`);
console.log(`chapters -> src/dashboard/demoChapters.ts (${chapters.length})`);
